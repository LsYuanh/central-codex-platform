struct Handle {
    HANDLE value = nullptr;
    ~Handle() { if (value && value != INVALID_HANDLE_VALUE) CloseHandle(value); }
    Handle() = default;
    Handle(const Handle&) = delete;
    Handle& operator=(const Handle&) = delete;
};
static void require(bool ok, const char* operation) {
    if (!ok) throw std::runtime_error(std::string(operation) + ": " + std::to_string(GetLastError()));
}
static std::wstring quote(const std::wstring& value) {
    // All inputs are absolute paths generated by this probe and contain no quotes.
    if (value.find(L'"') != std::wstring::npos) throw std::runtime_error("Invalid path");
    return L"\"" + value + L"\"";
}
static void write(const fs::path& path, const std::string& value) {
    std::ofstream stream(path); stream << value; stream.close();
    if (!stream) throw std::runtime_error("Probe output write failed");
}
static DWORD accessError(const fs::path& path, DWORD access) {
    Handle file;
    file.value = CreateFileW(path.c_str(), access, FILE_SHARE_READ | FILE_SHARE_WRITE,
        nullptr, OPEN_EXISTING, FILE_ATTRIBUTE_NORMAL, nullptr);
    return file.value == INVALID_HANDLE_VALUE ? GetLastError() : ERROR_SUCCESS;
}
