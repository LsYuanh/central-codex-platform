static int child(const fs::path& root, unsigned short port, bool hold, bool spawnBaseline = false) {
    const fs::path own = root / L"alice";
    if (hold) { write(own / L"ready", "ready"); Sleep(30000); return 0; }
    Handle token;
    require(OpenProcessToken(GetCurrentProcess(), TOKEN_QUERY, &token.value) != 0, "Child token");
    DWORD appContainer = 0, bytes = 0;
    require(GetTokenInformation(token.value, TokenIsAppContainer, &appContainer,
        sizeof(appContainer), &bytes) != 0, "Container identity");
    const DWORD ownRead = accessError(own / L"input", GENERIC_READ);
    const DWORD centralRead = accessError(root / L"central-canary", GENERIC_READ);
    const DWORD centralWrite = accessError(root / L"central-canary", GENERIC_WRITE);
    const DWORD otherRead = accessError(root / L"bob" / L"input", GENERIC_READ);
    const DWORD hardlinkRead = accessError(own / L"canary-link", GENERIC_READ);
    write(own / L"output", "ALICE_CLIENT_SIMULATION_NOT_REAL_MODEL");
    WSADATA data{}; require(WSAStartup(MAKEWORD(2, 2), &data) == 0, "Winsock");
    SOCKET socket = ::socket(AF_INET, SOCK_STREAM, IPPROTO_TCP);
    sockaddr_in address{}; address.sin_family = AF_INET; address.sin_port = htons(port);
    InetPtonW(AF_INET, L"127.0.0.1", &address.sin_addr);
    u_long nonblocking = 1; ioctlsocket(socket, FIONBIO, &nonblocking);
    int connected = connect(socket, reinterpret_cast<sockaddr*>(&address), sizeof(address));
    int networkError = connected == 0 ? 0 : WSAGetLastError();
    // Nonblocking connect can initially report WSAEWOULDBLOCK even when WFP
    // subsequently denies it. Inspect completion rather than that intermediate
    // state, and never count a timeout as proof of denied network access.
    if (networkError == WSAEWOULDBLOCK) {
        fd_set writable, failed; FD_ZERO(&writable); FD_ZERO(&failed);
        FD_SET(socket, &writable); FD_SET(socket, &failed);
        timeval timeout{5, 0};
        int selected = select(0, nullptr, &writable, &failed, &timeout);
        if (selected == 0) networkError = WSAETIMEDOUT;
        else if (selected == SOCKET_ERROR) networkError = WSAGetLastError();
        else {
            int length = sizeof(networkError);
            if (getsockopt(socket, SOL_SOCKET, SO_ERROR,
                    reinterpret_cast<char*>(&networkError), &length) == SOCKET_ERROR)
                networkError = WSAGetLastError();
        }
    }
    closesocket(socket); WSACleanup();
    wchar_t environment[64]{};
    bool inherited = GetEnvironmentVariableW(L"YUAN_QA_PARENT_ONLY", environment, 64) != 0;
    std::wstring command = quote((root / L"probe.exe").wstring()) + L" --hold " + quote(root.wstring()) + L" 0";
    STARTUPINFOW startup{}; startup.cb = sizeof(startup); PROCESS_INFORMATION process{};
    BOOL spawned = CreateProcessW((root / L"probe.exe").c_str(), command.data(), nullptr, nullptr,
        FALSE, CREATE_NO_WINDOW, nullptr, own.c_str(), &startup, &process);
    DWORD spawnError = spawned ? 0 : GetLastError();
    bool descendantReady = false;
    if (spawned) {
        if (spawnBaseline) {
            for (int i = 0; i < 100 && !fs::exists(own / L"ready"); i++) Sleep(50);
            descendantReady = fs::exists(own / L"ready") && WaitForSingleObject(process.hProcess, 0) == WAIT_TIMEOUT;
        }
        require(TerminateProcess(process.hProcess, 12) != 0, "Stop synthetic descendant");
        require(WaitForSingleObject(process.hProcess, 5000) == WAIT_OBJECT_0, "Wait synthetic descendant");
        CloseHandle(process.hThread); CloseHandle(process.hProcess); }
    bool ok = appContainer == 1 && ownRead == 0 && centralRead == ERROR_ACCESS_DENIED &&
        centralWrite == ERROR_ACCESS_DENIED && otherRead == ERROR_ACCESS_DENIED &&
        hardlinkRead == ERROR_ACCESS_DENIED && networkError == WSAEACCES &&
        !spawned && spawnError == ERROR_NOT_ENOUGH_QUOTA && !inherited;
    if (spawnBaseline) ok = appContainer == 1 && spawned && descendantReady && spawnError == 0;
    std::ostringstream json;
    json << "{\"appContainer\":" << appContainer << ",\"ownReadError\":" << ownRead
         << ",\"ownWrite\":true,\"centralReadError\":" << centralRead << ",\"centralWriteError\":" << centralWrite
         << ",\"otherUserReadError\":" << otherRead << ",\"hardlinkReadError\":" << hardlinkRead
         << ",\"loopbackConnectError\":" << networkError << ",\"childCreateError\":" << spawnError
         << ",\"descendantReady\":" << (descendantReady ? "true" : "false")
         << ",\"parentEnvironmentInherited\":" << (inherited ? "true" : "false")
         << ",\"passed\":" << (ok ? "true" : "false") << "}";
    write(own / L"result.json", json.str()); return ok ? 0 : 1;
}
