static void modelStdio(HANDLE input, HANDLE output, HANDLE process) {
    std::atomic<bool> ended{false}, failed{false}, stopping{false};
    std::thread reader([&] {
        char chunk[8192]; DWORD received = 0;
        while (!stopping && ReadFile(GetStdHandle(STD_INPUT_HANDLE), chunk, sizeof(chunk), &received, nullptr) && received) {
            DWORD written = 0;
            if (!WriteFile(input, chunk, received, &written, nullptr) || written != received) {
                failed = true; break;
            }
        }
        ended = true;
    });
    const auto stopReader = [&] {
        stopping = true;
        // Repeat cancellation until the thread exits: one cancellation can
        // race with the interval immediately before a synchronous ReadFile.
        const ULONGLONG deadline = GetTickCount64() + 5000;
        while (WaitForSingleObject(reader.native_handle(), 0) != WAIT_OBJECT_0) {
            CancelSynchronousIo(reader.native_handle());
            if (WaitForSingleObject(reader.native_handle(), 20) == WAIT_OBJECT_0) break;
            if (GetTickCount64() >= deadline) {
                // Fail closed: terminating this QA launcher closes its Job.
                // The missing summary/cleanup evidence makes the test fail.
                TerminateProcess(GetCurrentProcess(), 15); std::terminate();
            }
        }
        reader.join();
    };
    try {
        const ULONGLONG deadline = GetTickCount64() + 180000;
        while (!ended && GetTickCount64() < deadline) {
            DWORD available = 0;
            require(PeekNamedPipe(output, nullptr, 0, nullptr, &available, nullptr) != 0, "Model runtime stdout");
            if (available) {
                char chunk[8192]; DWORD received = 0, written = 0;
                require(ReadFile(output, chunk, std::min(available, static_cast<DWORD>(sizeof(chunk))), &received, nullptr) != 0, "Model runtime read");
                require(WriteFile(GetStdHandle(STD_OUTPUT_HANDLE), chunk, received, &written, nullptr) && written == received, "Model runtime forward");
            } else {
                if (WaitForSingleObject(process, 0) != WAIT_TIMEOUT) throw std::runtime_error("Model runtime exited unexpectedly");
                Sleep(10);
            }
        }
        if (!ended) throw std::runtime_error("Model runtime qualification timeout");
        if (failed) throw std::runtime_error("Model runtime stdin failed");
    } catch (...) {
        stopReader(); throw;
    }
    stopReader();
}
