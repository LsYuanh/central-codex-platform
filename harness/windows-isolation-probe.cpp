static void createQaJunction(const fs::path& link, const fs::path& target) {
    if (!fs::create_directory(link)) throw std::runtime_error("QA junction path must be newly created");
    Handle directory;
    directory.value = CreateFileW(link.c_str(), GENERIC_WRITE, 0, nullptr, OPEN_EXISTING,
        FILE_FLAG_OPEN_REPARSE_POINT | FILE_FLAG_BACKUP_SEMANTICS, nullptr);
    require(directory.value != INVALID_HANDLE_VALUE, "Open new QA junction");
    const std::wstring substitute = L"\\??\\" + target.wstring(), display = target.wstring();
    const WORD substituteBytes = static_cast<WORD>(substitute.size() * sizeof(wchar_t));
    const WORD displayBytes = static_cast<WORD>(display.size() * sizeof(wchar_t));
    const WORD dataBytes = static_cast<WORD>(8 + substituteBytes + displayBytes + 2 * sizeof(wchar_t));
    struct JunctionHeader { DWORD tag; WORD dataBytes, reserved, substituteOffset, substituteBytes, displayOffset, displayBytes; };
    std::vector<unsigned char> buffer(8 + dataBytes, 0);
    auto header = reinterpret_cast<JunctionHeader*>(buffer.data());
    *header = {IO_REPARSE_TAG_MOUNT_POINT, dataBytes, 0, 0, substituteBytes,
        static_cast<WORD>(substituteBytes + sizeof(wchar_t)), displayBytes};
    memcpy(buffer.data() + sizeof(JunctionHeader), substitute.c_str(), substituteBytes);
    memcpy(buffer.data() + sizeof(JunctionHeader) + substituteBytes + sizeof(wchar_t), display.c_str(), displayBytes);
    DWORD returned = 0;
    require(DeviceIoControl(directory.value, FSCTL_SET_REPARSE_POINT, buffer.data(), static_cast<DWORD>(buffer.size()),
        nullptr, 0, &returned, nullptr) != 0, "Set synthetic QA junction");
}
