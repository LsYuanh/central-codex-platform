static void grant(const fs::path& path, PSID sid, DWORD access, bool directory) {
    PACL oldAcl = nullptr, newAcl = nullptr;
    PSECURITY_DESCRIPTOR descriptor = nullptr;
    DWORD result = GetNamedSecurityInfoW(path.c_str(), SE_FILE_OBJECT,
        DACL_SECURITY_INFORMATION, nullptr, nullptr, &oldAcl, nullptr, &descriptor);
    if (result != ERROR_SUCCESS) throw std::runtime_error("Read probe ACL: " + std::to_string(result));
    EXPLICIT_ACCESSW entry{};
    entry.grfAccessPermissions = access; entry.grfAccessMode = GRANT_ACCESS;
    entry.grfInheritance = directory ? SUB_CONTAINERS_AND_OBJECTS_INHERIT : NO_INHERITANCE;
    entry.Trustee.TrusteeForm = TRUSTEE_IS_SID; entry.Trustee.TrusteeType = TRUSTEE_IS_UNKNOWN;
    entry.Trustee.ptstrName = static_cast<LPWSTR>(sid);
    result = SetEntriesInAclW(1, &entry, oldAcl, &newAcl);
    if (result == ERROR_SUCCESS) result = SetNamedSecurityInfoW(const_cast<LPWSTR>(path.c_str()),
        SE_FILE_OBJECT, DACL_SECURITY_INFORMATION, nullptr, nullptr, newAcl, nullptr);
    LocalFree(newAcl); LocalFree(descriptor);
    if (result != ERROR_SUCCESS) throw std::runtime_error("Grant probe ACL: " + std::to_string(result));
}
