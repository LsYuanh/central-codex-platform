static std::string jsonPath(const fs::path& path) {
    std::wstring wide = path.wstring();
    int size = WideCharToMultiByte(CP_UTF8, WC_ERR_INVALID_CHARS, wide.data(), static_cast<int>(wide.size()), nullptr, 0, nullptr, nullptr);
    require(size > 0, "UTF-8 path size");
    std::string utf8(static_cast<size_t>(size), '\0');
    require(WideCharToMultiByte(CP_UTF8, WC_ERR_INVALID_CHARS, wide.data(), static_cast<int>(wide.size()), utf8.data(), size, nullptr, nullptr) == size, "UTF-8 path");
    std::string escaped;
    for (char value : utf8) {
        if (static_cast<unsigned char>(value) < 32) throw std::runtime_error("Control character in path");
        if (value == '\\' || value == '"') escaped.push_back('\\');
        escaped.push_back(value);
    }
    return escaped;
}
static void waitReply(HANDLE pipe, HANDLE process, const std::string& id, std::string& transcript) {
    ULONGLONG deadline = GetTickCount64() + 30000;
    while (GetTickCount64() < deadline) {
        DWORD available = 0;
        if (!PeekNamedPipe(pipe, nullptr, 0, nullptr, &available, nullptr)) {
            DWORD pipeError = GetLastError(), exitCode = STILL_ACTIVE;
            WaitForSingleObject(process, 1000); GetExitCodeProcess(process, &exitCode);
            throw std::runtime_error("Runtime stdout error: " + std::to_string(pipeError) + "; process exit: " + std::to_string(exitCode));
        }
        if (available) {
            char chunk[4096]; DWORD received = 0;
            require(ReadFile(pipe, chunk, std::min(available, static_cast<DWORD>(sizeof(chunk))), &received, nullptr) != 0, "Read runtime stdout");
            transcript.append(chunk, received);
            if (transcript.size() > 4 * 1024 * 1024) throw std::runtime_error("Runtime transcript limit");
            if (transcript.find("\"" + id + "\"") != std::string::npos && transcript.back() == '\n') return;
        }
        else if (WaitForSingleObject(process, 0) == WAIT_OBJECT_0) {
            DWORD code = 0; GetExitCodeProcess(process, &code);
            throw std::runtime_error("Runtime exited before RPC response: " + std::to_string(code));
        }
        Sleep(20);
    }
    throw std::runtime_error("Runtime RPC timeout: " + id);
}
