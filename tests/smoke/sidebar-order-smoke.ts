import assert from "node:assert/strict";
import {emptyLayout,readLayout,orderedThreads,sidebarGroup,moveThread,promoteThread} from "../../apps/desktop/src/sidebar-order.ts";
const snapshot={id:"a",name:"A",folders:["C:/original"],revision:1};
const rows=[{id:"1",clientProject:snapshot},{id:"2",clientProject:snapshot},{id:"3"}];
let state=moveThread(emptyLayout(),rows,"1","b","2",true);
assert.deepEqual(orderedThreads(rows,state).map(t=>t.id),["2","1","3"]);
assert.equal(sidebarGroup(rows[0],state,new Set(["a","b"])),"b");
assert.deepEqual(rows[0].clientProject,snapshot);
state=readLayout(JSON.stringify({version:1,...state}));
assert.equal(sidebarGroup(rows[0],state,new Set(["a"])),null,"deleted destination does not restore source grouping");
state=moveThread(state,orderedThreads(rows,state),"1",null);
assert.equal(sidebarGroup(rows[0],state,new Set(["a","b"])),null);
state=promoteThread(state,orderedThreads(rows,state),"2","turn:x");
assert.equal(state.order[0],"2");
state=moveThread(state,orderedThreads(rows,state),"2","a","1",true);
assert.equal(promoteThread(state,orderedThreads(rows,state),"2","turn:x"),state,"stream chunks must not undo a manual move within the same turn");
state=promoteThread(state,orderedThreads(rows,state),"2","turn:y");
assert.equal(state.order[0],"2");
assert.throws(()=>moveThread(state,rows,"missing",null));
assert.throws(()=>readLayout('{"version":1}'));
console.log("SIDEBAR_ORDER_OK: move/reorder, explicit recent, deleted group, immutable execution snapshot, persistence, per-turn activity dedup");
