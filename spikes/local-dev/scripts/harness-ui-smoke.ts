import assert from "node:assert/strict";
import { clientGitDiff, normalizeGatewayUiEvent, reduceExecutions, type ExecutionActivity } from "../apps/desktop/src/gateway-ui-events.ts";

const event = (method: string, params: Record<string, unknown> = {}) => normalizeGatewayUiEvent({method, params}, 1000);
const start = event("device/tool/started", {requestId:"a",threadId:"thread-a",turnId:"turn-a",deviceId:"client-a",tool:"device_exec"});
let rows: ExecutionActivity[] = reduceExecutions([], start);
assert.equal(rows[0].phase, "dispatched", "broker dispatch is not client execution acknowledgement");
const log = event("device/tool/output", {requestId:"a",eventSequence:1,stream:"stdout",chunk:"本机测试\n"});
rows = reduceExecutions(rows, log);
assert.equal(rows[0].phase, "executing", "client stdout is execution evidence");
rows = reduceExecutions(rows, start);
assert.equal(rows[0].logs.length, 1, "duplicate start preserves output");
rows = reduceExecutions(rows, log);
assert.equal(rows[0].logs.length, 1, "duplicate output is ignored");
rows = reduceExecutions(rows, event("device/tool/started", {requestId:"b",threadId:"thread-b"}));
rows = reduceExecutions(rows, event("device/tool/completed", {requestId:"a",status:"failed",errorCode:"COMMAND_TIMEOUT",exitCode:124}), 2000);
assert.equal(rows[0].status, "timed_out");
assert.equal(rows[1].status, "running", "completion belongs to one execution/thread");
rows = reduceExecutions(rows, start);
rows = reduceExecutions(rows, event("device/tool/output", {requestId:"a",eventSequence:2,stream:"stdout",chunk:"late"}));
assert.equal(rows[0].status, "timed_out", "late start cannot revive completed execution");
assert.equal(rows[0].logs.length, 1, "late output does not alter final execution");
rows = reduceExecutions(rows, event("gateway/disconnected"), 3000);
assert.equal(rows[1].status, "unknown");
rows = reduceExecutions(rows, event("device/tool/completed", {requestId:"b",status:"cancelled"}));
assert.equal(rows[1].status, "cancelled", "authoritative final event reconciles unknown result");
rows = reduceExecutions(rows, event("device/tool/completed", {requestId:"c",threadId:"thread-c",status:"denied"}));
rows = reduceExecutions(rows, event("device/tool/started", {requestId:"c",threadId:"thread-c"}));
assert.equal(rows[2].status, "denied", "completion before start is retained");
rows = reduceExecutions(rows, event("device/tool/started", {requestId:"d"}));
rows = reduceExecutions(rows, event("device/status", {agent:"offline"}));
assert.equal(rows[3].status, "unknown", "device loss alone makes active result unknown");
assert.equal(normalizeGatewayUiEvent({method:"device/tool/output",params:{requestId:"x",eventSequence:NaN,stream:"stdout"}}).kind, "invalid");
assert.equal(event("output/state", {output:{id:"invalid"}}).kind, "invalid");
const userInput = normalizeGatewayUiEvent({id:"question", method:"item/tool/requestUserInput", params:{threadId:"thread-b",questions:[]}});
assert.equal(userInput.kind === "approval" && userInput.approval.kind, "user-input", "native user questions remain interactive");
assert.equal(userInput.kind === "approval" && userInput.approval.threadId, "thread-b");
assert.equal(normalizeGatewayUiEvent({id:1,method:"item/commandExecution/requestApproval",params:{}}).kind, "approval");
assert.equal(normalizeGatewayUiEvent({id:1,method:"item/tool/call",params:{}}).kind, "protocol", "legacy dynamic-tool bridge remains explicit");
assert.equal(event("serverRequest/resolved", {requestId:"question"}).kind, "approval-resolved");
const capabilities = event("gateway/capabilities", {remoteWorkspace:true,imageGeneration:false,plugins:false,subagents:false});
assert.equal(capabilities.kind === "capabilities" && capabilities.capabilities.imageGeneration, false);
const patchApproval = normalizeGatewayUiEvent({id:"patch",method:"device/fileChange/requestApproval",requestKind:"approval",params:{threadId:"thread-a",deviceId:"client-a",patch:"*** Begin Patch"}});
assert.equal(patchApproval.kind === "approval" && patchApproval.approval.method, "device/fileChange/requestApproval");
const saving = event("output/state", {output:{id:"file",threadId:"thread-a",deviceId:"client-a",name:"file.png",source:"generatedImage",kind:"image",status:"saving"}});
assert.equal(saving.kind, "output");
assert.equal(reduceExecutions(rows, saving), rows, "file save state never changes execution terminal state");
rows = reduceExecutions([], start);
rows = reduceExecutions(rows, event("device/tool/output", {requestId:"a",eventSequence:1,stream:"stdout",chunk:"中".repeat(400_000)}));
assert.ok(new TextEncoder().encode(rows[0].logs[0].chunk).length <= 1024*1024);
assert.equal(rows[0].truncated, true, "one oversized frame is also bounded");
const diff = {source:"client",path:".",repositoryRoot:"C:/client/project",format:"git-unified-diff",stdout:"diff --git a/a b/a\n",stderr:"",exitCode:0,truncated:false,staged:false};
assert.equal(clientGitDiff(diff).repositoryRoot, "C:/client/project");
assert.throws(() => clientGitDiff({...diff,source:"central"}));
assert.throws(() => clientGitDiff({...diff,exitCode:1}));
rows = reduceExecutions([], event("device/tool/completed", {requestId:"diff",threadId:"thread-a",status:"succeeded",result:diff}));
assert.equal(rows[0].diff?.source, "client", "actual diff appears on the corresponding execution");
const terminal = event("device/tool/completed", {requestId:"offline",status:"offline"});
assert.equal(terminal.kind === "execution-end" && terminal.status, "offline");
const partial = {outcome:"partial",applied:[{path:"a.txt",version:"v2"}],failedPath:"b.txt",atomic:false,retrySafe:false};
rows = reduceExecutions([], event("device/tool/completed", {requestId:"patch",status:"failed",result:partial}));
assert.equal(rows[0].patch?.applied[0].path, "a.txt", "partial failures retain applied-file evidence");
assert.equal(rows[0].patch?.retrySafe, false);
rows = reduceExecutions([], start);
const runtimeLost = event("gateway/runtimeUnavailable", {error:"App Server exited"});
assert.equal(runtimeLost.kind, "runtime-unavailable", "engine failure is separate from device/socket connectivity");
assert.ok(runtimeLost.kind === "runtime-unavailable" && runtimeLost.error.includes("管理员重启"));
rows = reduceExecutions(rows, runtimeLost);
assert.equal(rows[0].status, "unknown");
assert.equal(event("device/status", {agent:"online"}).kind, "device");
console.log("HARNESS_UI_SMOKE_OK");
